import type { LlmSelection } from "../providers/LlmSelection.ts";
import type { MessageEditDraft } from "../sessions/inputs/MessageEdit.ts";
import type { SessionSnapshot } from "../sessions/SessionSnapshot.ts";
import type { UserImage } from "../sessions/transcript/Messages.ts";
import type {
  ContinuationReceipt,
  ContinuationSubmission,
} from "../sessions/inputs/Continuation.ts";
import type {
  MessageRefusalReason,
  UserMessageReceipt,
  UserMessageSubmission,
} from "../sessions/inputs/UserMessageSubmission.ts";

// State and journal for a single chat.
export interface ChatState {
  draft: string;
  draftVersion: number;
  draftImages: readonly UserImage[];
  draftImagesVersion: number;
  selection: LlmSelection | null;
  pending: PendingSubmission | null;
  pendingContinuation: PendingContinuation | null;
  messageEdit?: MessageEditDraft | undefined;
  knownExecutionId: string | null;
  title: string;
  titleProvenance: TitleProvenance;
  error: string | null;
}

// Distinguishes the placeholder from a title generated by the session backend.
export type TitleProvenance = "placeholder" | "generated";

// Journal for an in-flight or uncertain message submission.
export interface PendingSubmission {
  original: UserMessageSubmission;
  draftVersion: number;
  draftImagesVersion: number;
  status: "sending" | "uncertain";
  preserveDraft?: boolean;
}

// Journal for an in-flight or uncertain continuation.
export interface PendingContinuation {
  original: ContinuationSubmission;
  status: "sending" | "uncertain";
}

const refusalErrors: Record<MessageRefusalReason, string> = {
  staleRevision: "The conversation changed. Review it before sending again.",
  capacity: "The session cannot accept another message yet.",
  stopping: "The execution is stopping. Wait before sending again.",
  selectionLocked: "The model selection is locked for this execution.",
};

// A read begun after this receipt can prove settlement even after another client
// pushes the execution out of the recent window. Earlier idle reads cannot.
export function executionSettled(
  snapshot: SessionSnapshot,
  executionId: string,
  knownWhenRead: string | null,
): boolean {
  return (
    snapshot.lastSettlement?.executionId === executionId ||
    (knownWhenRead === executionId &&
      snapshot.unsettledExecutionId !== executionId &&
      snapshot.queuedInputExecutionId !== executionId)
  );
}

export function idleChatSelection(
  chat: ChatState | undefined,
  snapshot: SessionSnapshot | null,
  defaultSelection: LlmSelection | null,
): LlmSelection | null {
  return chat?.selection ?? snapshot?.latestLlmSelection ?? defaultSelection;
}

export function newChat(selection: LlmSelection | null): ChatState {
  return {
    draft: "",
    draftVersion: 0,
    draftImages: [],
    draftImagesVersion: 0,
    selection,
    pending: null,
    pendingContinuation: null,
    knownExecutionId: null,
    title: "New chat",
    titleProvenance: "placeholder",
    error: null,
  };
}

export function editDraft(chat: ChatState, text: string): ChatState {
  if (!isRevision(chat.draftVersion + 1)) throw new TypeError("Draft version is out of range.");
  return { ...chat, draft: text, draftVersion: chat.draftVersion + 1 };
}

export function appendDraftImage(chat: ChatState, image: UserImage): ChatState {
  if (!isUserImage(image)) throw new TypeError("Invalid image.");
  if (chat.draftImages.some((item) => item.imageId === image.imageId)) return chat;
  if (!isRevision(chat.draftImagesVersion + 1))
    throw new TypeError("Image version is out of range.");
  return {
    ...chat,
    draftImages: [...chat.draftImages, { ...image }],
    draftImagesVersion: chat.draftImagesVersion + 1,
  };
}

export function removeDraftImage(chat: ChatState, imageId: string): ChatState {
  if (!chat.draftImages.some((image) => image.imageId === imageId)) return chat;
  if (!isRevision(chat.draftImagesVersion + 1))
    throw new TypeError("Image version is out of range.");
  return {
    ...chat,
    draftImages: chat.draftImages.filter((image) => image.imageId !== imageId),
    draftImagesVersion: chat.draftImagesVersion + 1,
  };
}

export function beginSubmission(
  chat: ChatState,
  original: UserMessageSubmission,
  preserveDraft = false,
): ChatState {
  if (!isSubmission(original)) throw new TypeError("Invalid original submission.");
  return {
    ...chat,
    pending: {
      original: copySubmission(original),
      draftVersion: chat.draftVersion,
      draftImagesVersion: chat.draftImagesVersion,
      status: "sending",
      ...(preserveDraft ? { preserveDraft: true } : {}),
    },
    error: null,
  };
}

export function beginContinuation(chat: ChatState, original: ContinuationSubmission): ChatState {
  if (!isContinuationSubmission(original)) throw new TypeError("Invalid original continuation.");
  return {
    ...chat,
    pendingContinuation: { original: copyContinuationSubmission(original), status: "sending" },
    error: null,
  };
}

export function applyContinuationReceipt(
  chat: ChatState,
  sessionId: string,
  receipt: unknown,
): ChatState {
  if (!isContinuationReceipt(receipt)) throw new TypeError("Invalid continuation receipt.");
  if (receipt.sessionId !== sessionId) throw new TypeError("Receipt belongs to another session.");
  const pending = chat.pendingContinuation;
  if (pending === null || pending.original.operationId !== receipt.operationId)
    throw new TypeError("Receipt does not match the original continuation.");
  return {
    ...chat,
    pendingContinuation: null,
    knownExecutionId: receipt.executionId,
    error: null,
  };
}

export function applyReceipt(chat: ChatState, sessionId: string, receipt: unknown): ChatState {
  if (!isReceipt(receipt)) throw new TypeError("Invalid message receipt.");
  if (receipt.sessionId !== sessionId) throw new TypeError("Receipt belongs to another session.");
  const pending = chat.pending;
  if (pending === null || !sameSubmission(pending.original, receipt.submission))
    throw new TypeError("Receipt does not match the original submission.");

  const accepted = receipt.acceptance === "accepted";
  const clearDraft =
    pending.preserveDraft !== true &&
    accepted &&
    pending.draftVersion === chat.draftVersion &&
    chat.draft === pending.original.text;
  return {
    ...chat,
    draft: clearDraft ? "" : chat.draft,
    draftImages:
      pending.preserveDraft !== true &&
      accepted &&
      pending.draftImagesVersion === chat.draftImagesVersion
        ? []
        : chat.draftImages,
    pending: null,
    knownExecutionId: receipt.executionId,
    error: receipt.refusalReason === null ? null : refusalErrors[receipt.refusalReason],
  };
}

export function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

export function isId(value: unknown): value is string {
  return typeof value === "string" && value.trim().length > 0;
}

export function isUserImage(value: unknown): value is UserImage {
  return (
    isRecord(value) &&
    isId(value.imageId) &&
    typeof value.width === "number" &&
    Number.isSafeInteger(value.width) &&
    value.width > 0 &&
    typeof value.height === "number" &&
    Number.isSafeInteger(value.height) &&
    value.height > 0
  );
}

function isRevision(value: unknown): value is number {
  return typeof value === "number" && Number.isSafeInteger(value) && value >= 0;
}

function isNullableString(value: unknown): value is string | null {
  return value === null || typeof value === "string";
}

function isNullableContextWindow(value: unknown): value is number | null {
  return value === null || (typeof value === "number" && Number.isSafeInteger(value) && value > 0);
}

export function isSelection(value: unknown): value is LlmSelection | null {
  if (value === null) return true;
  if (!isRecord(value) || !isRecord(value.connection)) return false;
  const connection = value.connection;
  return (
    isId(connection.id) &&
    typeof connection.name === "string" &&
    (connection.route === "openAI" ||
      connection.route === "chatGpt" ||
      connection.route === "custom") &&
    (connection.api === "openAIResponses" || connection.api === "openAIChatCompletions") &&
    isId(connection.endpoint) &&
    (connection.authentication === "none" ||
      connection.authentication === "apiKey" ||
      connection.authentication === "oAuth") &&
    isId(value.modelId) &&
    (value.family === "openAI" ||
      value.family === "anthropic" ||
      value.family === "google" ||
      value.family === "other") &&
    typeof value.supportsImages === "boolean" &&
    isNullableContextWindow(value.contextWindow) &&
    isNullableString(value.reasoningEffort)
  );
}

function isContinuationSubmission(value: unknown): value is ContinuationSubmission {
  return (
    isRecord(value) &&
    isId(value.operationId) &&
    isRevision(value.expectedHistoryRevision) &&
    isId(value.expectedLastExecutionId) &&
    isSelection(value.llmSelection) &&
    value.llmSelection !== null
  );
}

function isContinuationReceipt(value: unknown): value is ContinuationReceipt {
  return (
    isRecord(value) &&
    isId(value.sessionId) &&
    isId(value.operationId) &&
    isId(value.executionId) &&
    value.executionId === value.operationId
  );
}

function copyContinuationSubmission(original: ContinuationSubmission): ContinuationSubmission {
  return {
    ...original,
    llmSelection: {
      ...original.llmSelection,
      connection: { ...original.llmSelection.connection },
    },
  };
}

function isSubmission(value: unknown): value is UserMessageSubmission {
  return (
    isRecord(value) &&
    isId(value.submissionId) &&
    isRevision(value.expectedHistoryRevision) &&
    typeof value.text === "string" &&
    (value.imageIds == null || (Array.isArray(value.imageIds) && value.imageIds.every(isId))) &&
    isSelection(value.llmSelection)
  );
}

function isRefusalReason(value: unknown): value is MessageRefusalReason {
  return typeof value === "string" && Object.hasOwn(refusalErrors, value);
}

function isReceipt(value: unknown): value is UserMessageReceipt {
  if (
    !isRecord(value) ||
    !isId(value.sessionId) ||
    !isSubmission(value.submission) ||
    value.submission.llmSelection === null
  )
    return false;
  if (value.acceptance === "accepted")
    return value.refusalReason === null && isId(value.executionId);
  return (
    value.acceptance === "refused" &&
    isRefusalReason(value.refusalReason) &&
    value.executionId === null
  );
}

function sameSelection(left: LlmSelection | null, right: LlmSelection | null): boolean {
  if (left === null || right === null) return left === right;
  return (
    left.modelId === right.modelId &&
    left.family === right.family &&
    left.supportsImages === right.supportsImages &&
    left.contextWindow === right.contextWindow &&
    left.reasoningEffort === right.reasoningEffort &&
    left.connection.id === right.connection.id &&
    left.connection.name === right.connection.name &&
    left.connection.route === right.connection.route &&
    left.connection.api === right.connection.api &&
    left.connection.endpoint === right.connection.endpoint &&
    left.connection.authentication === right.connection.authentication
  );
}

function sameSubmission(left: UserMessageSubmission, right: UserMessageSubmission): boolean {
  return (
    left.submissionId === right.submissionId &&
    left.expectedHistoryRevision === right.expectedHistoryRevision &&
    left.text === right.text &&
    (left.imageIds ?? []).length === (right.imageIds ?? []).length &&
    (left.imageIds ?? []).every((id, index) => id === right.imageIds?.[index]) &&
    sameSelection(left.llmSelection, right.llmSelection)
  );
}

function copySubmission(original: UserMessageSubmission): UserMessageSubmission {
  const selection = original.llmSelection;
  return {
    ...original,
    ...(original.imageIds ? { imageIds: [...original.imageIds] } : {}),
    llmSelection:
      selection === null ? null : { ...selection, connection: { ...selection.connection } },
  };
}

function isMessageEdit(value: unknown): value is MessageEditDraft | undefined {
  if (value === undefined) return true;
  if (!isRecord(value) || !isRecord(value.target)) return false;
  const target = value.target;
  if (
    !isId(target.executionId) ||
    !isId(target.entryId) ||
    target.kind !== "user" ||
    !isRevision(target.historyRevision) ||
    typeof value.text !== "string" ||
    (value.images !== undefined &&
      (!Array.isArray(value.images) ||
        !value.images.every(isUserImage) ||
        new Set(value.images.map((image) => image.imageId)).size !== value.images.length)) ||
    !isNullableString(value.error) ||
    !["loading", "editing", "saving", "uncertain"].includes(String(value.status))
  )
    return false;
  const original = value.submission;
  if (value.status === "loading" || value.status === "editing") return original === undefined;
  if (!isRecord(original) || !isRecord(original.message)) return false;
  return (
    isId(original.operationId) &&
    original.text === value.text &&
    (original.imageIds == null ||
      (Array.isArray(original.imageIds) &&
        original.imageIds.every(isId) &&
        original.imageIds.length === (Array.isArray(value.images) ? value.images.length : 0) &&
        original.imageIds.every(
          (id, index) => id === (value.images as UserImage[] | undefined)?.[index]?.imageId,
        ))) &&
    original.message.executionId === target.executionId &&
    original.message.messageId === target.entryId &&
    original.message.role === "user" &&
    original.message.historyRevision === target.historyRevision &&
    original.llmSelection !== null &&
    isSelection(original.llmSelection)
  );
}

export function isChat(value: unknown): value is ChatState {
  if (
    !isRecord(value) ||
    !isRevision(value.draftVersion) ||
    !isRevision(value.draftImagesVersion) ||
    !Array.isArray(value.draftImages) ||
    !value.draftImages.every(isUserImage) ||
    new Set(value.draftImages.map((image) => image.imageId)).size !== value.draftImages.length
  )
    return false;
  const pending = value.pending;
  return (
    typeof value.draft === "string" &&
    isMessageEdit(value.messageEdit) &&
    isSelection(value.selection) &&
    (value.knownExecutionId === null || isId(value.knownExecutionId)) &&
    (value.pendingContinuation === null ||
      (isRecord(value.pendingContinuation) &&
        isContinuationSubmission(value.pendingContinuation.original) &&
        (value.pendingContinuation.status === "sending" ||
          value.pendingContinuation.status === "uncertain"))) &&
    (value.pendingContinuation === null ||
      (pending === null && value.messageEdit === undefined && value.knownExecutionId === null)) &&
    typeof value.title === "string" &&
    (value.titleProvenance === "placeholder" || value.titleProvenance === "generated") &&
    isNullableString(value.error) &&
    (pending === null ||
      (isRecord(pending) &&
        isSubmission(pending.original) &&
        isRevision(pending.draftVersion) &&
        pending.draftVersion <= value.draftVersion &&
        isRevision(pending.draftImagesVersion) &&
        pending.draftImagesVersion <= value.draftImagesVersion &&
        (pending.preserveDraft === undefined || typeof pending.preserveDraft === "boolean") &&
        (pending.status === "sending" || pending.status === "uncertain")))
  );
}
